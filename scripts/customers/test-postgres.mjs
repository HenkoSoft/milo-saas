  const concurrent = await Promise.all([service.saveCustomer(form({}),false),service.saveCustomer(form({}),false)]);
  assert.ok(concurrent.some(r=>r.status==="saved")); assert.ok(concurrent.every(r=>["saved","conflict"].includes(r.status)));
  assert.equal((await db.query('SELECT count(*)::int AS n FROM (SELECT "tenantId","commercialNumber" FROM customers GROUP BY 1,2 HAVING count(*)>1) x')).rows[0].n,0);
  phase = "cleanup-owned-isolated-database";
  await prisma.$disconnect(); prisma=null; await db.end(); db=null;
  const identity=(await admin.query("SELECT shobj_description(oid,'pg_database') AS marker FROM pg_database WHERE datname=$1",[name])).rows;
  assert.equal(identity[0].marker,marker);
  assert.equal((await admin.query("SELECT count(*)::int AS n FROM pg_stat_activity WHERE datname=$1",[name])).rows[0].n,0);
  await admin.query(`DROP DATABASE "${name}"`);created=false;
  console.log("PASS: isolated migration, legacy compatibility, real persistence, OWNER/ADMIN, tenant isolation, validation, concurrency, delete allowed/blocked, audit retention/rollback, constraints; temporary database removed. No milo_dev connection or writes.");
